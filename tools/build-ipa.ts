// Build the per-word IPA table used by the lessons.
//
//   npm run build:ipa
//
// Reads the sentence texts from src/lib/intonation/lessons.ts, looks every word up in CMUdict
// (cmu-pronouncing-dictionary, ISC license), syllabifies it with our own maximal-onset syllabifier and maps ARPAbet
// to US IPA (src/lib/ipa/). Writes src/lib/intonation/ipa.generated.json, which lessons.ts reads at import time.
// A word that is not in CMUdict (and has no override) stops the build with an error: we never guess.
// GPL tools (espeak-ng, phonemizer) are deliberately not used.

import { readFileSync, writeFileSync } from "node:fs";
import { dictionary } from "cmu-pronouncing-dictionary";
import { buildWordIpa, wordsOfSentence } from "../src/lib/ipa/words.ts";
import { OVERRIDES } from "../src/lib/ipa/overrides.ts";
import type { WordIpa } from "../src/lib/ipa/words.ts";

const LESSONS = new URL("../src/lib/intonation/lessons.ts", import.meta.url);
const OUT = new URL("../src/lib/intonation/ipa.generated.json", import.meta.url);

/** Sentence texts: every `text: "..."` that is immediately followed by `kind:` in lessons.ts. */
function lessonSentenceTexts(source: string): string[] {
  const texts = [...source.matchAll(/\btext:\s*"([^"]+)",\s*\n\s*kind:/g)].map((m) => m[1]);
  if (texts.length === 0) throw new Error("No sentences found in lessons.ts (expected `text: \"...\",` before `kind:`)");
  return texts;
}

function main() {
  const words: string[] = [];
  for (const text of lessonSentenceTexts(readFileSync(LESSONS, "utf8"))) {
    for (const w of wordsOfSentence(text)) if (!words.includes(w)) words.push(w);
  }

  const missing: string[] = [];
  const table: Record<string, WordIpa> = {};
  for (const w of [...words].sort()) {
    try {
      table[w] = buildWordIpa(w, dictionary, OVERRIDES);
    } catch (e) {
      missing.push(e instanceof Error ? e.message : String(e));
    }
  }
  if (missing.length > 0) {
    console.error(`\nbuild-ipa failed for ${missing.length} word(s):\n- ${missing.join("\n- ")}\n`);
    process.exit(1);
  }

  const json = {
    _comment:
      "Generated by tools/build-ipa.ts (npm run build:ipa) from CMUdict. Do not edit by hand; add overrides in the script.",
    words: table,
  };
  writeFileSync(OUT, JSON.stringify(json, null, 2) + "\n");
  console.log(`Wrote ${Object.keys(table).length} words to src/lib/intonation/ipa.generated.json`);
  for (const [w, e] of Object.entries(table)) console.log(`  ${w.padEnd(8)} ${e.ipa.padEnd(10)} ${e.arpabet}${e.source === "override" ? "  (override)" : ""}`);
}

main();
