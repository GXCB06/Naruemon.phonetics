// Build the lesson content files.
//
//   npm run build:lessons
//
// Reads the authored sources in content/source/<unit>/<lesson>.json (text, nucleus word, kind, spelling chunks)
// and writes content/units/<unit>/<lesson>.json: full `Sentence` objects with IPA and syllables from CMUdict
// (via src/lib/ipa/) and pitch levels from levelsForGroup. Deterministic: same input, same bytes.
// A word that is not in CMUdict (and has no override) stops the build; we never guess.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dictionary } from "cmu-pronouncing-dictionary";
import { buildSentence, lessonWords } from "../src/lib/intonation/buildLesson.ts";
import type { LessonSource } from "../src/lib/intonation/buildLesson.ts";
import { OVERRIDES } from "../src/lib/ipa/overrides.ts";
import { buildWordIpa } from "../src/lib/ipa/words.ts";
import type { WordIpa } from "../src/lib/ipa/words.ts";

const SOURCE = new URL("../content/source/", import.meta.url);
const OUT = new URL("../content/units/", import.meta.url);

function main() {
  let files = 0;
  let sentences = 0;
  for (const unit of readdirSync(SOURCE, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    mkdirSync(new URL(`${unit.name}/`, OUT), { recursive: true });
    for (const f of readdirSync(new URL(`${unit.name}/`, SOURCE)).filter((n) => n.endsWith(".json")).sort()) {
      const src = JSON.parse(readFileSync(new URL(`${unit.name}/${f}`, SOURCE), "utf8")) as LessonSource;
      const table: Record<string, WordIpa> = {};
      for (const w of lessonWords(src)) table[w] = buildWordIpa(w, dictionary, OVERRIDES);
      const out = {
        _comment: "Generated by tools/build-lessons.ts (npm run build:lessons) from content/source. Do not edit by hand.",
        id: src.id,
        unit: src.unit,
        sentences: src.sentences.map((s) => buildSentence(s, table)),
      };
      writeFileSync(new URL(`${unit.name}/${f}`, OUT), JSON.stringify(out, null, 2) + "\n");
      files++;
      sentences += out.sentences.length;
      console.log(`  ${unit.name}/${f}: ${out.sentences.length} sentences`);
    }
  }
  console.log(`Wrote ${files} lesson files (${sentences} sentences) to content/units/`);
}

main();
