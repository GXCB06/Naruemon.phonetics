// Build the IPA table for IPA practice.
//
//   npm run build:ipa-practice
//
// Reads src/lib/ipa/practiceWords.ts, looks every word up in CMUdict (cmu-pronouncing-dictionary, ISC license) with the
// same syllabifier and ARPAbet→IPA map as the lessons, and writes src/lib/ipa/practice.generated.json.
// A word that is not in CMUdict (and has no override) stops the build: we never guess a pronunciation.

import { writeFileSync } from "node:fs";
import { dictionary } from "cmu-pronouncing-dictionary";
import { OVERRIDES } from "../src/lib/ipa/overrides.ts";
import { PRACTICE_WORDS } from "../src/lib/ipa/practiceWords.ts";
import { buildWordIpa } from "../src/lib/ipa/words.ts";
import type { WordIpa } from "../src/lib/ipa/words.ts";

const OUT = new URL("../src/lib/ipa/practice.generated.json", import.meta.url);

function main() {
  const missing: string[] = [];
  const table: Record<string, WordIpa> = {};
  for (const { word } of PRACTICE_WORDS) {
    try {
      table[word] = buildWordIpa(word, dictionary, OVERRIDES);
    } catch (e) {
      missing.push(e instanceof Error ? e.message : String(e));
    }
  }
  if (missing.length > 0) {
    console.error(`\nbuild-ipa-practice failed for ${missing.length} word(s):\n- ${missing.join("\n- ")}\n`);
    process.exit(1);
  }
  const json = {
    _comment: "Generated by tools/build-ipa-practice.ts (npm run build:ipa-practice) from CMUdict. Do not edit by hand.",
    words: table,
  };
  writeFileSync(OUT, JSON.stringify(json, null, 2) + "\n");
  console.log(`Wrote ${Object.keys(table).length} words to src/lib/ipa/practice.generated.json`);
  for (const [w, e] of Object.entries(table)) console.log(`  ${w.padEnd(10)} ${e.ipa.padEnd(14)} ${e.arpabet}`);
}

main();
