import type { Metadata, Viewport } from "next";
import { Noto_Sans, Noto_Sans_Thai, Nunito } from "next/font/google";
import "./globals.css";

const nunito = Nunito({ variable: "--nf-ui", subsets: ["latin"] });
// Noto Sans latin-ext covers the IPA Extensions block (ɪ ʃ ə ɚ ʊ ɹ ð ŋ) and stress marks (ˈ ˌ).
const notoIpa = Noto_Sans({ variable: "--nf-ipa", subsets: ["latin", "latin-ext"] });
const notoThai = Noto_Sans_Thai({ variable: "--nf-thai", subsets: ["thai"] });

export const metadata: Metadata = {
  title: "Myna — intonation coach",
  description: "Practise English intonation: say it or draw it, and see your pitch against the textbook pattern.",
  applicationName: "Myna",
  // Added to the home screen, Myna opens full screen (no Safari bars). The manifest (app/manifest.ts) covers
  // Android/Chrome and iOS 16.4+; the apple-* tags cover older iPadOS. Icons come from app/icon.svg, favicon.ico and
  // apple-icon.png (generated by tools/make-icons.ts).
  appleWebApp: { capable: true, title: "Myna", statusBarStyle: "default" },
  formatDetection: { telephone: false, email: false, address: false, date: false },
  other: { "apple-mobile-web-app-capable": "yes" },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  // Draw under the notch/home indicator; globals.css and the fixed bars pad with env(safe-area-inset-*).
  viewportFit: "cover",
  themeColor: [
    { media: "(prefers-color-scheme: light)", color: "#fffbf2" },
    { media: "(prefers-color-scheme: dark)", color: "#15131f" },
  ],
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html lang="en" className={`${nunito.variable} ${notoIpa.variable} ${notoThai.variable} h-full antialiased`}>
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
